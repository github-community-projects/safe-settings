jest.mock('../../lib/installationCache', () => ({
  getInstallations: jest.fn(),
  getOrgLogins: jest.fn(),
  getLastFetchedAt: jest.fn()
}))

const { setupRoutes } = require('../../lib/routes')
const env = require('../../lib/env')
const { getInstallations, getOrgLogins } = require('../../lib/installationCache')
const { loadAndMergeSettings } = require('../../lib/hubSyncHandler')

describe('installation sync status authentication', () => {
  let robot
  let hub
  let spoke
  let handler
  let res
  const hubPath = '.github/safe-settings/organizations/spoke-org'
  const content = value => ({ data: { content: Buffer.from(value).toString('base64'), encoding: 'base64' } })
  const generatedSettings = source => `# Auto-generated by Safe-Settings Hub-Sync
# Source: organizations/spoke-org/settings.yml only
# DO NOT EDIT THIS FILE DIRECTLY - Edit source files in hub-org/hub

${source}`

  beforeEach(() => {
    jest.replaceProperty(env, 'ADMIN_REPO', 'admin')
    jest.replaceProperty(env, 'CONFIG_PATH', '.github')
    jest.replaceProperty(env, 'SAFE_SETTINGS_HUB_PATH', 'safe-settings')
    jest.replaceProperty(env, 'SAFE_SETTINGS_HUB_ORG', 'hub-org')
    jest.replaceProperty(env, 'SAFE_SETTINGS_HUB_REPO', 'hub')
    jest.replaceProperty(process, 'env', { ...process.env, SAFE_SETTINGS_HUB_ORG: 'hub-org', SAFE_SETTINGS_HUB_REPO: 'hub' })
    getInstallations.mockResolvedValue([
      { id: 1, account: { type: 'Organization', login: 'HUB-ORG' } },
      { id: 2, account: { type: 'Organization', login: 'spoke-org' } }
    ])
    getOrgLogins.mockReturnValue(['spoke-org'])
    hub = {
      rest: {
        repos: {
          getContent: jest.fn(async params => {
            if (params.owner !== 'hub-org') throw new Error('Hub client cannot read spoke')
            if (params.path === hubPath) {
              return { data: [{ type: 'file', name: 'settings.yml', path: `${hubPath}/settings.yml` }] }
            }
            if (params.path === '.github/safe-settings/globals/settings.yml') {
              throw Object.assign(new Error('Not found'), { status: 404 })
            }
            return content('organization settings')
          })
        }
      }
    }
    spoke = {
      rest: {
        repos: {
          get: jest.fn().mockResolvedValue({}),
          getContent: jest.fn(async params => {
            if (params.owner !== 'spoke-org') throw new Error('Spoke client cannot read private hub')
            return params.path === '.github'
              ? { data: [{ type: 'file', name: 'settings.yml', path: '.github/settings.yml' }] }
              : content(generatedSettings('organization settings'))
          }),
          listCommits: jest.fn().mockResolvedValue({ data: [] })
        }
      }
    }
    robot = {
      auth: jest.fn(async id => {
        if (id === 1) return hub
        if (id === 2) return spoke
        throw new Error(`Unexpected installation ${id}`)
      }),
      log: { info: jest.fn(), debug: jest.fn(), warn: jest.fn(), error: jest.fn() }
    }
    const router = setupRoutes(robot, jest.fn())
    handler = router.stack.find(layer => layer.route && layer.route.path === '/api/safe-settings/installation').route.stack[0].handle
    res = { status: jest.fn().mockReturnThis(), json: jest.fn() }
  })

  it('uses separate installation clients for matching private hub and spoke content', async () => {
    await handler({ query: {} }, res)

    expect(res.status).not.toHaveBeenCalled()
    expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
      installations: expect.arrayContaining([expect.objectContaining({ account: 'spoke-org', isInSync: true })])
    }))
    expect(robot.auth.mock.calls).toEqual([[1], [2]])
    expect(hub.rest.repos.getContent).toHaveBeenCalledWith({ owner: 'hub-org', repo: 'hub', path: hubPath, ref: 'main' })
    expect(hub.rest.repos.getContent).toHaveBeenCalledWith({
      owner: 'hub-org', repo: 'hub', path: '.github/safe-settings/globals/settings.yml', ref: 'main'
    })
    expect(hub.rest.repos.getContent).toHaveBeenCalledWith({
      owner: 'hub-org', repo: 'hub', path: `${hubPath}/settings.yml`, ref: 'main'
    })
    expect(spoke.rest.repos.getContent.mock.calls).toEqual([
      [{ owner: 'spoke-org', repo: 'admin', path: '.github' }],
      [{ owner: 'spoke-org', repo: 'admin', path: '.github/settings.yml' }]
    ])
    expect(res.json.mock.calls[0][0].hubSync).toEqual({ status: 'available' })
    expect(robot.log.error).not.toHaveBeenCalled()
  })

  it('reports that sync status is unavailable when Hub-Sync is not configured', async () => {
    const { SAFE_SETTINGS_HUB_ORG: _org, SAFE_SETTINGS_HUB_REPO: _repo, ...rest } = process.env
    jest.replaceProperty(process, 'env', rest)

    await handler({ query: {} }, res)

    expect(robot.auth.mock.calls).toEqual([[2]])
    expect(hub.rest.repos.getContent).not.toHaveBeenCalled()
    expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
      hubSync: { status: 'not_configured' },
      installations: expect.arrayContaining([expect.objectContaining({ account: 'spoke-org', isInSync: false })])
    }))
    expect(robot.log.warn).not.toHaveBeenCalled()
  })

  it('still reports differing content as out of sync', async () => {
    spoke.rest.repos.getContent.mockImplementation(async params => {
      if (params.owner !== 'spoke-org') throw new Error('Spoke client cannot read private hub')
      return params.path === '.github'
        ? { data: [{ type: 'file', name: 'settings.yml', path: '.github/settings.yml' }] }
        : content('different settings')
    })

    await handler({ query: {} }, res)

    expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
      installations: expect.arrayContaining([expect.objectContaining({ account: 'spoke-org', isInSync: false })])
    }))
    expect(robot.log.error).not.toHaveBeenCalled()
  })

  describe('nested configuration sync status', () => {
    const managedFiles = {
      'settings.yml': 'organization settings',
      'repos/settings.yml': 'repository settings',
      'suborgs/division/settings.yml': 'division settings'
    }

    function mockContents (client, owner, root, files) {
      const entries = new Map([[root, []]])
      for (const [relativePath, value] of Object.entries(files)) {
        const parts = relativePath.split('/')
        let parent = root
        for (const [index, name] of parts.entries()) {
          const entryPath = `${parent}/${name}`
          const isFile = index === parts.length - 1
          if (!entries.has(entryPath)) {
            entries.get(parent).push({ type: isFile ? 'file' : 'dir', name, path: entryPath })
            entries.set(entryPath, isFile ? value : [])
          }
          parent = entryPath
        }
      }
      client.rest.repos.getContent.mockImplementation(async params => {
        if (params.owner !== owner) throw new Error(`Wrong installation client for ${params.owner}`)
        if (!entries.has(params.path)) throw Object.assign(new Error(`Not found: ${params.path}`), { status: 404 })
        const value = entries.get(params.path)
        return Array.isArray(value) ? { data: value } : content(value)
      })
    }

    function deployedFiles (hubFiles) {
      return Object.fromEntries(Object.entries(hubFiles).map(([relativePath, value]) => [
        relativePath,
        relativePath === 'settings.yml' ? generatedSettings(value) : value
      ]))
    }

    async function expectSyncStatus (hubFiles, spokeFiles, isInSync) {
      mockContents(hub, 'hub-org', hubPath, hubFiles)
      mockContents(spoke, 'spoke-org', '.github', spokeFiles)

      await handler({ query: {} }, res)

      expect(res.status).not.toHaveBeenCalled()
      expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
        installations: expect.arrayContaining([expect.objectContaining({ account: 'spoke-org', isInSync })])
      }))
    }

    it('compares matching nested files by relative path, including duplicate basenames', async () => {
      await expectSyncStatus(managedFiles, deployedFiles(managedFiles), true)

      for (const relativePath of Object.keys(managedFiles)) {
        expect(spoke.rest.repos.getContent).toHaveBeenCalledWith({
          owner: 'spoke-org', repo: 'admin', path: `.github/${relativePath}`
        })
        expect(hub.rest.repos.getContent).toHaveBeenCalledWith(expect.objectContaining({
          owner: 'hub-org', repo: 'hub', path: `${hubPath}/${relativePath}`
        }))
      }
      for (const directory of ['repos', 'suborgs', 'suborgs/division']) {
        expect(hub.rest.repos.getContent).toHaveBeenCalledWith({
          owner: 'hub-org', repo: 'hub', path: `${hubPath}/${directory}`, ref: 'main'
        })
      }
      expect(robot.log.error).not.toHaveBeenCalled()
    })

    it('compares generated settings after merging global and organization sources', async () => {
      const orgSource = 'repository:\n  has_wiki: false\n'
      const globalSource = 'repository:\n  has_issues: true\n'
      const hubFiles = { 'settings.yml': orgSource }
      mockContents(hub, 'hub-org', hubPath, hubFiles)
      mockContents(spoke, 'spoke-org', '.github', { 'settings.yml': orgSource })
      const hubGetContent = hub.rest.repos.getContent.getMockImplementation()
      hub.rest.repos.getContent.mockImplementation(async params => {
        if (params.path === '.github/safe-settings/globals/settings.yml') return content(globalSource)
        return hubGetContent(params)
      })

      const expectedSettings = await loadAndMergeSettings(robot, hub, 'spoke-org', 'main')
      expect(expectedSettings).not.toBe(orgSource)
      expect(expectedSettings).not.toBe(globalSource)
      const spokeGetContent = spoke.rest.repos.getContent.getMockImplementation()
      spoke.rest.repos.getContent.mockImplementation(async params => {
        if (params.path === '.github/settings.yml') return content(expectedSettings)
        return spokeGetContent(params)
      })

      await handler({ query: {} }, res)

      expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
        installations: expect.arrayContaining([expect.objectContaining({ account: 'spoke-org', isInSync: true })])
      }))
      expect(hub.rest.repos.getContent).toHaveBeenCalledWith({
        owner: 'hub-org', repo: 'hub', path: '.github/safe-settings/globals/settings.yml', ref: 'main'
      })
      expect(robot.log.error).not.toHaveBeenCalled()
    })

    it.each(['repos/settings.yml', 'suborgs/division/settings.yml'])('reports stale %s as out of sync', async relativePath => {
      await expectSyncStatus(managedFiles, { ...deployedFiles(managedFiles), [relativePath]: 'stale settings' }, false)
      expect(robot.log.error).not.toHaveBeenCalled()
    })

    it.each(['repos/settings.yml', 'suborgs/division/settings.yml'])('reports missing %s as out of sync', async relativePath => {
      const spokeFiles = deployedFiles(managedFiles)
      delete spokeFiles[relativePath]
      await expectSyncStatus(managedFiles, spokeFiles, false)
    })

    it('reports a missing file inside an existing nested directory as out of sync', async () => {
      const spokeFiles = deployedFiles(managedFiles)
      delete spokeFiles['repos/settings.yml']
      await expectSyncStatus(managedFiles, {
        ...spokeFiles,
        'repos/other.yml': 'unrelated settings'
      }, false)
    })

    it('supports configurations with only nested files', async () => {
      const files = { 'repos/example.yml': 'repository settings' }
      await expectSyncStatus(files, files, true)
      expect(robot.log.error).not.toHaveBeenCalled()
    })

    it('does not mistake a directory for a matching empty nested file', async () => {
      await expectSyncStatus({ 'repos/empty.yml': '' }, { 'repos/empty.yml/other.yml': '' }, false)
      expect(robot.log.error).toHaveBeenCalledWith(expect.stringContaining('Expected readable file content at .github/repos/empty.yml'))
    })

    it('ignores extra spoke files and directories not managed by the hub', async () => {
      await expectSyncStatus(managedFiles, {
        ...deployedFiles(managedFiles),
        'repos/local.yml': 'local settings',
        'workflows/ci.yml': 'local workflow'
      }, true)
      expect(robot.log.error).not.toHaveBeenCalled()
    })

    it('does not report success when reading a nested hub directory fails', async () => {
      mockContents(hub, 'hub-org', hubPath, managedFiles)
      mockContents(spoke, 'spoke-org', '.github', managedFiles)
      const getContent = hub.rest.repos.getContent.getMockImplementation()
      hub.rest.repos.getContent.mockImplementation(async params => {
        if (params.path === `${hubPath}/repos`) throw new Error('Nested directory unavailable')
        return getContent(params)
      })

      await handler({ query: {} }, res)

      expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
        installations: expect.arrayContaining([expect.objectContaining({ account: 'spoke-org', isInSync: false })])
      }))
      expect(robot.log.error).toHaveBeenCalledWith(expect.stringContaining('Nested directory unavailable'))
    })

    it('does not report success when a nested hub listing is not a directory', async () => {
      mockContents(hub, 'hub-org', hubPath, managedFiles)
      mockContents(spoke, 'spoke-org', '.github', managedFiles)
      const getContent = hub.rest.repos.getContent.getMockImplementation()
      hub.rest.repos.getContent.mockImplementation(async params => {
        if (params.path === `${hubPath}/repos`) return content('not a directory')
        return getContent(params)
      })

      await handler({ query: {} }, res)

      expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
        installations: expect.arrayContaining([expect.objectContaining({ account: 'spoke-org', isInSync: false })])
      }))
      expect(robot.log.error).toHaveBeenCalledWith(expect.stringContaining('Expected a directory listing for hub path'))
    })
  })

  it('preserves installation and commit information when the hub installation is missing', async () => {
    getInstallations.mockResolvedValue([{ id: 2, account: { type: 'Organization', login: 'spoke-org' } }])
    spoke.rest.repos.listCommits.mockResolvedValue({
      data: [{ sha: 'abc123', commit: { message: 'Update settings' } }]
    })

    await handler({ query: {} }, res)

    expect(robot.auth.mock.calls).toEqual([[2]])
    expect(res.status).not.toHaveBeenCalled()
    expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
      hubSync: { status: 'hub_not_installed', org: 'hub-org' },
      installations: [expect.objectContaining({
        account: 'spoke-org',
        hasConfigRepo: true,
        sha: 'abc123',
        message: 'Update settings',
        isInSync: false
      })]
    }))
    expect(hub.rest.repos.getContent).not.toHaveBeenCalled()
    expect(spoke.rest.repos.getContent).not.toHaveBeenCalled()
    expect(robot.log.warn).toHaveBeenCalledWith('Installation for hub org hub-org not found; skipping hub sync comparisons')
    expect(robot.log.error).not.toHaveBeenCalled()
  })

  it('reports hub authentication failures explicitly', async () => {
    const error = new Error('Hub authentication failed')
    robot.auth.mockRejectedValueOnce(error)

    await handler({ query: {} }, res)

    expect(res.status).toHaveBeenCalledWith(500)
    expect(res.json).toHaveBeenCalledWith({ error: error.message })
    expect(robot.log.error).toHaveBeenCalledWith(error)
    expect(spoke.rest.repos.get).not.toHaveBeenCalled()
  })

  it('does not require hub authentication when activity is disabled', async () => {
    getInstallations.mockResolvedValue([{ id: 2, account: { type: 'Organization', login: 'spoke-org' } }])

    await handler({ query: { disableActivity: 'true' } }, res)

    expect(robot.auth).not.toHaveBeenCalled()
    expect(res.status).not.toHaveBeenCalled()
    expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
      installations: [expect.objectContaining({ account: 'spoke-org' })]
    }))
  })
})

describe('hub content setup guidance', () => {
  let robot
  let handler
  let res

  beforeEach(() => {
    jest.replaceProperty(env, 'CONFIG_PATH', '.github')
    jest.replaceProperty(env, 'SAFE_SETTINGS_HUB_ORG', 'hub-org')
    jest.replaceProperty(env, 'SAFE_SETTINGS_HUB_REPO', 'hub')
    jest.replaceProperty(process, 'env', { ...process.env, SAFE_SETTINGS_HUB_ORG: 'hub-org', SAFE_SETTINGS_HUB_REPO: 'hub' })
    getInstallations.mockClear()
    getInstallations.mockResolvedValue([{ id: 1, account: { type: 'Organization', login: 'hub-org' } }])
    robot = {
      auth: jest.fn().mockResolvedValue({
        rest: {
          repos: {
            getContent: jest.fn().mockResolvedValue({ data: { type: 'file', name: 'settings.yml', path: '.github/settings.yml', sha: 'abc', size: 0, content: '', encoding: 'base64' } }),
            listCommits: jest.fn().mockResolvedValue({ data: [] })
          }
        }
      }),
      log: { info: jest.fn(), debug: jest.fn(), warn: jest.fn(), error: jest.fn() }
    }
    const router = setupRoutes(robot, jest.fn())
    handler = router.stack.find(layer => layer.route && layer.route.path === '/api/safe-settings/hub/content').route.stack[0].handle
    res = { status: jest.fn().mockReturnThis(), json: jest.fn() }
  })

  it.each(['SAFE_SETTINGS_HUB_ORG', 'SAFE_SETTINGS_HUB_REPO'])('explains that Hub-Sync is not set up when %s is not configured', async name => {
    const { [name]: _omitted, ...rest } = process.env
    jest.replaceProperty(process, 'env', rest)

    await handler({ params: {}, query: {} }, res)

    expect(res.status).toHaveBeenCalledWith(404)
    expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
      code: 'HUB_NOT_CONFIGURED',
      error: 'Safe-Settings Hub is not set up yet'
    }))
    expect(getInstallations).not.toHaveBeenCalled()
    expect(robot.auth).not.toHaveBeenCalled()
  })

  it('explains when the app is not installed on the hub organization', async () => {
    getInstallations.mockResolvedValue([{ id: 2, account: { type: 'Organization', login: 'spoke-org' } }])

    await handler({ params: {}, query: {} }, res)

    expect(res.status).toHaveBeenCalledWith(404)
    expect(res.json).toHaveBeenCalledWith(expect.objectContaining({
      code: 'HUB_INSTALLATION_NOT_FOUND',
      message: expect.stringContaining("Hub organization 'hub-org'")
    }))
    expect(robot.auth).not.toHaveBeenCalled()
  })

  it('loads hub content normally when Hub-Sync is configured', async () => {
    await handler({ params: {}, query: { recursive: 'false' } }, res)

    expect(robot.auth).toHaveBeenCalledWith(1)
    expect(res.json).not.toHaveBeenCalledWith(expect.objectContaining({ code: expect.any(String) }))
  })
})
